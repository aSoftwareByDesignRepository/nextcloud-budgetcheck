def apply_global(text: str, rules: list[tuple[str, str]]) -> str:
    for pattern, repl in rules:
        text = re.sub(pattern, repl, text)
    return text


def polish_file(path: Path, manual: dict, global_rules: list[tuple[str, str]]) -> None:
    data = load(path)
    out = {}
    for key, val in data["translations"].items():
        if key in manual:
            out[key] = manual[key]
        elif isinstance(val, list):
            out[key] = [apply_global(apply_global(v, global_rules), global_rules) for v in val]
        else:
            out[key] = apply_global(val, global_rules)
    data["translations"] = out
    save(path, data)


