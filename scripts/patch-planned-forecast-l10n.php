foreach ($locales as $lang) {
	$path = $base . '/' . $lang . '.json';
	if (!is_file($path)) {
		fwrite(STDERR, "Missing {$path}\n");
		exit(1);
	}
	$data = json_decode((string)file_get_contents($path), true, 512, JSON_THROW_ON_ERROR);
	$translations = $data['translations'] ?? [];
	$localePatch = $patch[$lang] ?? [];
	foreach ($localePatch as $key => $value) {
		$translations[$key] = $value;
	}
	ksort($translations, SORT_STRING);
	$data['translations'] = $translations;
	$encoded = json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES) . "\n";
	file_put_contents($path, $encoded);
	echo "Patched {$lang}.json (" . count($localePatch) . " strings)\n";
}

echo "planned-forecast l10n patch OK.\n";
